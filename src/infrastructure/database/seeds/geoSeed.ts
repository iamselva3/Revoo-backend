export async function seedGeoDataIfNeeded() {
  try {
    // 1. States Seeding / Upsert
    const stateCount = await IndiaStateModel.countDocuments();
    if (stateCount < ALL_INDIA_STATES.length) {
      console.log(`[GeoSeeder] Upserting all 28 States and 8 Union Territories...`);
      for (const st of ALL_INDIA_STATES) {
        await IndiaStateModel.updateOne(
          { name: st.name },
          { $set: st },
          { upsert: true }
        );
      }
      console.log(`[GeoSeeder] Successfully synced ${ALL_INDIA_STATES.length} States and UTs.`);
    }

    // 2. Comprehensive Locations Seeding / Upsert (Including Tier A, B, and C towns like Srivilliputhur)
    const locationCount = await IndiaLocationModel.countDocuments();
    if (locationCount < COMPREHENSIVE_INDIAN_LOCATIONS.length) {
      console.log(`[GeoSeeder] Upserting comprehensive Tier A, B & C Indian cities & towns (${COMPREHENSIVE_INDIAN_LOCATIONS.length} entries)...`);
      
      const bulkOps = COMPREHENSIVE_INDIAN_LOCATIONS.map((loc) => ({
        updateOne: {
          filter: { city: loc.city, state: loc.state },
          update: { $set: loc },
          upsert: true,
        },
      }));

      await IndiaLocationModel.bulkWrite(bulkOps);
      console.log(`[GeoSeeder] Successfully synced ${COMPREHENSIVE_INDIAN_LOCATIONS.length} Indian cities, Tier B/C towns and PIN codes into MongoDB.`);
    } else {
      console.log(`[GeoSeeder] MongoDB location collection healthy with ${locationCount} indexed Indian locations.`);
    }
  } catch (err) {
    console.error('[GeoSeeder] Error checking or seeding India Geo data:', err);
  }
}
